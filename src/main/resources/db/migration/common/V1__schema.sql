CREATE TABLE manufacturer (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL,
    deleted BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE client (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(255) NOT NULL,
    email                VARCHAR(255) NOT NULL,
    password             VARCHAR(255) NOT NULL,
    card                 VARCHAR(255) NOT NULL,
    role                 VARCHAR(20)  NOT NULL DEFAULT 'USER',
    blocked              BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted              BOOLEAN      NOT NULL DEFAULT FALSE,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    password_expires_at  TIMESTAMP
);
CREATE INDEX idx_client_email ON client (email);

CREATE TABLE employee (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(255) NOT NULL,
    email                VARCHAR(255) NOT NULL,
    password             VARCHAR(255) NOT NULL,
    department           VARCHAR(255) NOT NULL,
    role                 VARCHAR(20)  NOT NULL DEFAULT 'EMPLOYEE',
    blocked              BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted              BOOLEAN      NOT NULL DEFAULT FALSE,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    password_expires_at  TIMESTAMP
);
CREATE INDEX idx_employee_email ON employee (email);

CREATE TABLE appliance (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255)   NOT NULL,
    category        VARCHAR(20)    NOT NULL,
    model           VARCHAR(255)   NOT NULL,
    manufacturer_id BIGINT         NOT NULL REFERENCES manufacturer (id),
    power_type      VARCHAR(20)    NOT NULL,
    characteristic  VARCHAR(255),
    description     VARCHAR(1000),
    power           INTEGER        NOT NULL,
    price           NUMERIC(19, 2) NOT NULL,
    deleted         BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_appliance_manufacturer ON appliance (manufacturer_id);

CREATE TABLE orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approved    BOOLEAN NOT NULL DEFAULT FALSE,
    client_id   BIGINT  REFERENCES client (id),
    employee_id BIGINT  REFERENCES employee (id),
    deleted     BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_orders_client ON orders (client_id);

CREATE TABLE order_row (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orders_id    BIGINT         REFERENCES orders (id),
    appliance_id BIGINT         NOT NULL REFERENCES appliance (id),
    amount       NUMERIC(19, 2) NOT NULL,
    number       BIGINT         NOT NULL,
    deleted      BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_order_row_orders ON order_row (orders_id);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_email VARCHAR(255) NOT NULL,
    actor_role  VARCHAR(20)  NOT NULL,
    action      VARCHAR(50)  NOT NULL,
    entity_type VARCHAR(50)  NOT NULL,
    entity_id   BIGINT,
    details     VARCHAR(1000)
);
CREATE INDEX idx_audit_log_created ON audit_log (created_at);
